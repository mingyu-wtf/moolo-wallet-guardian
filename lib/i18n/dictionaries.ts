export type TranslationKey = keyof typeof koreanDictionary;

export function isTranslationKey(value: string): value is TranslationKey {
  return Object.prototype.hasOwnProperty.call(koreanDictionary, value);
}

export function translateText(
  locale: Locale,
  key: TranslationKey,
  values?: Record<string, string | number>,
): string {
  const template: string = locale === "ko" ? koreanDictionary[key] : key;
  if (!values) return template;
  return Object.entries(values).reduce(
    (result, [name, value]) =>
      result.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function translateKnownText(locale: Locale, value: string): string {
  if (isTranslationKey(value)) return translateText(locale, value);
  if (locale === "en" || !value) return value;

  const patterns: Array<{
    expression: RegExp;
    render: (matches: RegExpMatchArray) => string;
  }> = [
    {
      expression: /^(.+) is running locally\.$/,
      render: (matches) =>
        `${translateKnownText(locale, matches[1])}을(를) 로컬에서 실행 중입니다.`,
    },
    {
      expression: /^(.+) is ready\.$/,
      render: (matches) =>
        `${translateKnownText(locale, matches[1])} 단계가 준비되었습니다.`,
    },
    {
      expression: /^(.+) restored to its deterministic intro state\.$/,
      render: (matches) =>
        `${translateKnownText(locale, matches[1])} 소개 상태를 동일한 초기값으로 복원했습니다.`,
    },
    {
      expression: /^(.+) opened\.$/,
      render: (matches) =>
        `${translateKnownText(locale, matches[1])} 시나리오를 열었습니다.`,
    },
    {
      expression: /^(.+): (.+)\.$/,
      render: (matches) =>
        `${translateKnownText(locale, matches[1])}: ${translateKnownText(locale, matches[2])}.`,
    },
    {
      expression: /^You only have (.+)\.$/,
      render: (matches) => `사용 가능한 잔액은 ${matches[1]}뿐입니다.`,
    },
    {
      expression: /^Transfer exceeds the \$(.+) policy limit$/,
      render: (matches) => `전송 금액이 $${matches[1]} 정책 한도를 초과함`,
    },
    {
      expression: /^AI agent request exceeds the \$(.+) daily limit$/,
      render: (matches) =>
        `AI 에이전트 요청이 $${matches[1]} 일일 한도를 초과함`,
    },
    {
      expression: /^(.+) needs (.+)\. Reset the demo to restore the starting balance\.$/,
      render: (matches) =>
        `${translateKnownText(locale, matches[1])}에 ${matches[2]}가 필요합니다. 시작 잔액을 복원하려면 데모를 초기화하세요.`,
    },
  ];

  for (const pattern of patterns) {
    const matches = value.match(pattern.expression);
    if (matches) return pattern.render(matches);
  }

  return value;
}
